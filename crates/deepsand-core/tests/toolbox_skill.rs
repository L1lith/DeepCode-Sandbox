//! The catalogue the agent is handed has to match the catalogue the app offers.
//!
//! `deepsand-toolbox` is installed into every sandbox and is the document the agent is told to
//! read before concluding that something is unavailable. It says, in as many words:
//!
//!     These are the ids. Anything not in this list does not exist as far as Deepsand is
//!     concerned.
//!
//! and a model that believes that refuses to use a tool that is sitting right there. Which is
//! what happened: the table omitted `xvfb`, `puppeteer`, `web-search` and `wrangler` while the
//! image had two of them built in, and the agent told the operator the sandbox had "no browser at
//! all -- I checked the tool catalogue" and then could not do the visual check it had been asked
//! for. The list is generated by hand from `tools::CATALOG`, so this is the check that says a
//! hand-written copy is still a copy.

use std::path::PathBuf;

fn skill() -> String {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("runtime")
        .join("skills")
        .join("deepsand-toolbox")
        .join("SKILL.md");
    std::fs::read_to_string(&path)
        .unwrap_or_else(|err| panic!("could not read {}: {err}", path.display()))
}

/// Every tool the operator can select is named in the skill, because a tool the agent cannot
/// find in that list is a tool it will not ask for.
#[test]
fn the_skill_documents_every_tool_in_the_catalogue() {
    let text = skill();
    let missing: Vec<&str> = deepsand_core::tools::CATALOG
        .iter()
        .filter(|tool| !text.contains(&format!("`{}`", tool.id)))
        .map(|tool| tool.id)
        .collect();

    assert!(
        missing.is_empty(),
        "the toolbox skill does not mention {missing:?}. It tells the agent that anything absent \
         from that list does not exist, so a tool missing from it is a tool the agent will not \
         use -- even when it is already in the image."
    );
}

/// The two capabilities that are useless apart are described as two things, and the skill says how
/// to check and how to launch rather than what to assume. Each of these is a wall an agent hit
/// here: it concluded there was no browser at all, and even with one it could not have started it
/// without `--no-sandbox`, because a browser cannot keep its own sandbox inside this container.
#[test]
fn the_skill_says_how_to_check_for_a_browser_and_how_to_launch_one() {
    let text = skill();
    for expected in [
        "deepsand-display",
        "executablePath",
        "--no-sandbox",
        "/workspace/shot.png",
    ] {
        assert!(
            text.contains(expected),
            "the skill no longer says {expected:?}. An agent that does not know it has a browser \
             will not use one, and an agent that does not know about --no-sandbox will launch it, \
             fail with 'Failed to launch the browser process', and give up."
        );
    }
}
